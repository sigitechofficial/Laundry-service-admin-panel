/**
 * Writes public/firebase-messaging-sw.js from .env / .env.local
 * Uses LAUNDRY_FIREBASE_* or VITE_FIREBASE_* (same as the main app).
 * Missing local config produces a safe no-op worker; production validation is
 * enforced by vite.config.mjs.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

const env = {
  ...parseEnvFile(path.join(root, ".env")),
  ...parseEnvFile(path.join(root, ".env.local")),
};

const firebaseConfig = {
  apiKey: env.VITE_FIREBASE_API_KEY || env.LAUNDRY_FIREBASE_API_KEY || "",
  authDomain:
    env.VITE_FIREBASE_AUTH_DOMAIN || env.LAUNDRY_FIREBASE_AUTH_DOMAIN || "",
  projectId: env.VITE_FIREBASE_PROJECT_ID || env.LAUNDRY_FIREBASE_PROJECT_ID || "",
  storageBucket:
    env.VITE_FIREBASE_STORAGE_BUCKET || env.LAUNDRY_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId:
    env.VITE_FIREBASE_MESSAGING_SENDER_ID ||
    env.LAUNDRY_FIREBASE_MESSAGING_SENDER_ID ||
    "",
  appId: env.VITE_FIREBASE_APP_ID || env.LAUNDRY_FIREBASE_APP_ID || "",
};

const outPath = path.join(root, "public", "firebase-messaging-sw.js");
const hasCompleteConfig = Object.values(firebaseConfig).every(Boolean);

// Match Firebase compat line used in your Firebase Console / web app (10.12.x works with this project).
const FB_VERSION = "10.12.2";
const sw = hasCompleteConfig
  ? `/* Generated by npm run sync:fcm-sw — do not edit by hand */
importScripts("https://www.gstatic.com/firebasejs/${FB_VERSION}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${FB_VERSION}/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(firebaseConfig, null, 2)});

const messaging = firebase.messaging();

function resolveTitleBody(payload) {
  var n = payload && payload.notification ? payload.notification : {};
  var d = payload && payload.data ? payload.data : {};
  var title = n.title || d.title || d.alertType || "Laundry Admin";
  var body = n.body || d.body || d.message || "";
  return { title: String(title), body: String(body) };
}

messaging.onBackgroundMessage(function (payload) {
  var resolved = resolveTitleBody(payload || {});
  var d = (payload && payload.data) || {};
  self.registration.showNotification(resolved.title, {
    body: resolved.body,
    icon: "/images/logo.png",
    data: d,
    tag: d.alertType || d.type || "laundry-admin",
  });
});

self.addEventListener("notificationclick", function (event) {
  event.notification.close();
  var data = event.notification.data || {};
  var path = "/";
  if (data.alertType === "payment_failed" || data.type === "payment_failed") {
    path = "/orders/payment-failures";
  } else if (data.bookingId && String(data.bookingId) !== "0") {
    path = "/orders/order-details/" + data.bookingId;
  } else if (data.alertType || data.type) {
    path = "/admin-notification-settings";
  }
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then(function (clientList) {
      for (var i = 0; i < clientList.length; i++) {
        var client = clientList[i];
        if ("focus" in client) {
          client.focus();
          if ("navigate" in client) client.navigate(path);
          return;
        }
      }
      if (clients.openWindow) return clients.openWindow(path);
    })
  );
});
`
  : `/* Generated by npm run sync:fcm-sw — Firebase is not configured. */
self.addEventListener("notificationclick", function (event) {
  event.notification.close();
});
`;

fs.writeFileSync(outPath, sw, "utf8");
console.log(
  "Wrote",
  outPath,
  hasCompleteConfig ? `projectId=${firebaseConfig.projectId}` : "(FCM disabled)"
);
